const input = { participantId: 'p1', hint: 'Un indice', day: '2026-10-16', revision: 0 };
test('daily hint validation: exact payload, trimmed Unicode text, strict LF, dates and CAS bounds', () => {
  assert.deepEqual(validateDailyHint({ ...input, hint: ' \n Première ligne\nDeuxième ligne \n' }), { ...input, hint: 'Première ligne\nDeuxième ligne' });
  assert.equal([...validateDailyHint({ ...input, hint: '😀'.repeat(600) }).hint].length, 600);
  const formattedLimit = `**${'😀'.repeat(596)}**`;
  assert.equal(validateDailyHint({ ...input, hint: ` \n${formattedLimit}\n ` }).hint, formattedLimit);
  assert.throws(() => validateDailyHint({ ...input, hint: `**${'😀'.repeat(597)}**` }), 'Markdown markers count toward the limit');
  assert.equal(validateDailyHint({ ...input, day: '2028-02-29', revision: 2147483646 }).revision, 2147483646);
  for (let code = 0; code <= 159; code++) {
    if (code === 10 || (code > 31 && code < 127)) continue;
    assert.throws(() => validateDailyHint({ ...input, hint: `A${String.fromCharCode(code)}B` }), `control ${code}`);
    assert.throws(() => validateDailyHint({ ...input, hint: `${String.fromCharCode(code)}A` }), 'controls cannot be trimmed away');
  }
  for (const hint of ['', ' \n ', 'a'.repeat(601), '😀'.repeat(601), 'A\r\nB', null, 4]) assert.throws(() => validateDailyHint({ ...input, hint }));
  for (const participantId of ['', 'p'.repeat(101), 'A\n', 'A\u0085', null, 2]) assert.throws(() => validateDailyHint({ ...input, participantId }));
  for (const day of ['2026-02-29', '2026-04-31', '2026-13-01', '2026-00-01', '0000-01-01', '2026-1-01', '2026-10-16T00:00:00Z', null]) assert.throws(() => validateDailyHint({ ...input, day }));
  for (const revision of [-1, 0.5, '0', null, NaN, Infinity, 2147483647]) assert.throws(() => validateDailyHint({ ...input, revision }));
  for (const value of [null, [], {}, { ...input, teamId: 'forged' }, { ...input, [Symbol('extra')]: true }]) assert.throws(() => validateDailyHint(value));
  for (const field of Object.keys(input)) {
    const missing: Record<string, unknown> = { ...input }; delete missing[field];
    assert.throws(() => validateDailyHint(missing));
  }
});

test('daily hint schema has identity CASCADE, scoped primary key, expiry index and scalar constraints', () => {
  const config = getTableConfig(participantDailyHints);
  assert.deepEqual(config.primaryKeys[0].columns.map(column => column.name), ['team_id', 'participant_id']);
  assert.equal(config.foreignKeys.length, 1);
  assert.equal(config.foreignKeys[0].reference().foreignTable, participants);
  assert.equal(config.foreignKeys[0].onDelete, 'cascade');
  assert.deepEqual(config.foreignKeys[0].reference().foreignColumns.map(column => column.name), ['team_id', 'id']);
  assert.ok(config.columns.every(column => column.notNull && !/json/i.test(column.getSQLType())));
  assert.equal(config.indexes.length, 1);
});

test('PGlite: all migrations, daily hint CAS/isolation/roster rewrite/expiry and cascading deletion', async () => {
  const { PGlite } = await import('@electric-sql/pglite');
  const engine = new PGlite();
  const dialect = new PgDialect();
  try {
    // Discover every migration, including a future generated daily-hints one.
    const directory = new URL('../drizzle/', import.meta.url);
    for (const filename of readdirSync(directory).filter(name => /^\d+.*\.sql$/.test(name)).sort()) {
      await engine.exec(readFileSync(new URL(filename, directory), 'utf8'));
    }
    if (!(await engine.query("SELECT to_regclass('public.participant_daily_hints') AS name")).rows[0].name) {
      // No migration is generated by this feature. Derive temporary test DDL
      // directly from the schema (including its real CHECKs and composite FK).
      const config = getTableConfig(participantDailyHints);
      const definitions: SQL[] = config.columns.map(column => sql`${sql.identifier(column.name)} ${sql.raw(column.getSQLType())} NOT NULL`);
      for (const key of config.primaryKeys) definitions.push(sql`PRIMARY KEY (${sql.join(key.columns.map(column => sql.identifier(column.name)), sql`, `)})`);
      for (const key of config.foreignKeys) {
        const reference = key.reference();
        definitions.push(sql`FOREIGN KEY (${sql.join(reference.columns.map(column => sql.identifier(column.name)), sql`, `)}) REFERENCES ${reference.foreignTable} (${sql.join(reference.foreignColumns.map(column => sql.identifier(column.name)), sql`, `)}) ON DELETE CASCADE`);
      }
      for (const check of config.checks) definitions.push(sql`CONSTRAINT ${sql.identifier(check.name)} CHECK (${check.value})`);
      const ddl = dialect.sqlToQuery(sql`CREATE TABLE ${participantDailyHints} (${sql.join(definitions, sql`, `)})`);
      await engine.query(ddl.sql, ddl.params);
    }
    const client = {
      execute(query: SQL) {
        return { query, then(resolve: (value: unknown) => unknown, reject: (reason: unknown) => unknown) {
          const compiled = dialect.sqlToQuery(query);
          return engine.query(compiled.sql, compiled.params).then(resolve, reject);
        } };
      },
      batch(queries: { query: SQL }[]) {
        return engine.transaction(async tx => {
          const results = [];
          for (const query of queries) {
            const compiled = dialect.sqlToQuery(query.query);
            results.push(await tx.query(compiled.sql, compiled.params));
          }
          return results;
        });
      },
    } as unknown as Parameters<typeof saveDailyHint>[0];
    const a = 'a'.repeat(64), b = 'b'.repeat(64), workspace = '0'.repeat(64);
    const now = new Date('2026-10-16T10:00:00Z');
    await engine.query('INSERT INTO workspaces(id) VALUES($1)', [workspace]);
    for (const [id, name] of [[a, 'A'], [b, 'B']]) {
      await engine.query('INSERT INTO teams(id,workspace_id,name,duration,warning,sound) VALUES($1,$2,$3,120,30,true)', [id, workspace, name]);
      for (const person of ['p1', 'p2', 'removed']) await engine.query('INSERT INTO participants(team_id,id,name) VALUES($1,$2,$2)', [id, person]);
      for (const [position, person] of ['p2', 'p1'].entries()) await engine.query('INSERT INTO team_members(team_id,participant_id,position,present) VALUES($1,$2,$3,false)', [id, person, position]);
    }
    assert.deepEqual(await readDailyHints(client, a, now), { day: input.day, hints: [] });
    await assert.rejects(saveDailyHint(client, a, { ...input, revision: 1 }, now), { status: 409 });
    const saved = await saveDailyHint(client, a, { ...input, hint: '  Ligne 1\nLigne 2  ' }, now);
    assert.deepEqual(saved, { day: input.day, hints: [{ participantId: 'p1', hint: 'Ligne 1\nLigne 2', revision: 1 }] });
    await assert.rejects(saveDailyHint(client, a, input, now), { status: 409 });
    await saveDailyHint(client, b, { ...input, hint: 'Autre équipe' }, now);
    await saveDailyHint(client, a, { ...input, participantId: 'p2' }, now);
    assert.deepEqual((await readDailyHints(client, a, now)).hints.map(hint => hint.participantId), ['p2', 'p1'], 'roster order, even absent members');
    const writers = await Promise.allSettled([
      saveDailyHint(client, a, { ...input, hint: 'Premier', revision: 1 }, now),
      saveDailyHint(client, a, { ...input, hint: 'Second', revision: 1 }, now),
    ]);
    assert.equal(writers.filter(writer => writer.status === 'fulfilled').length, 1);
    assert.equal(writers.filter(writer => writer.status === 'rejected' && writer.reason.status === 409).length, 1);
    assert.equal((await readDailyHints(client, a, now)).hints[1].revision, 2);
    assert.equal((await readDailyHints(client, b, now)).hints[0].hint, 'Autre équipe');
    const winner = await readDailyHints(client, a, now);
    await engine.exec(`CREATE FUNCTION reject_hint_write() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'simulated database failure'; END $$;
      CREATE TRIGGER reject_hint_write BEFORE UPDATE ON participant_daily_hints FOR EACH ROW EXECUTE FUNCTION reject_hint_write();`);
    await assert.rejects(saveDailyHint(client, a, { ...input, hint: '**Non enregistré**', revision: 2 }, now), /simulated database failure/);
    assert.deepEqual(await readDailyHints(client, a, now), winner, 'a failed database transaction never returns success or changes the winner');
    await engine.exec('DROP TRIGGER reject_hint_write ON participant_daily_hints; DROP FUNCTION reject_hint_write();');
    assert.equal((await engine.query('SELECT revision FROM teams WHERE id=$1', [a])).rows[0].revision, 1);
    await assert.rejects(saveDailyHint(client, a, { ...input, participantId: 'removed' }, now), { status: 404 });
    await assert.rejects(saveDailyHint(client, a, { ...input, participantId: 'unknown' }, now), { status: 404 });
    await engine.query('INSERT INTO participants(team_id,id,name) VALUES($1,$2,$2)', [b, 'only-b']);
    await engine.query("INSERT INTO team_members(team_id,participant_id,position,present) VALUES($1,'only-b',2,true)", [b]);
    await assert.rejects(saveDailyHint(client, a, { ...input, participantId: 'only-b' }, now), { status: 404 });
    await assert.rejects(readDailyHints(client, 'c'.repeat(64), now), { status: 403 });
    await assert.rejects(saveDailyHint(client, 'c'.repeat(64), input, now), { status: 403 });
    await assert.rejects(saveDailyHint(client, a, { ...input, hint: '' }, now), { status: 400 });

    await engine.query("DELETE FROM team_members WHERE team_id=$1 AND participant_id='p1'", [a]);
    assert.equal((await readDailyHints(client, a, now)).hints.length, 1, 'removed roster identities are hidden');
    await assert.rejects(saveDailyHint(client, a, { ...input, revision: 2 }, now), { status: 404 });
    assert.equal((await engine.query("SELECT revision FROM participant_daily_hints WHERE team_id=$1 AND participant_id='p1'", [a])).rows[0].revision, 2, 'invalid member cannot alter an existing hint');
    await engine.query("INSERT INTO team_members(team_id,participant_id,position,present) VALUES($1,'p1',1,true)", [a]);
    assert.equal((await readDailyHints(client, a, now)).hints[1].revision, 2, 'membership delete/reinsert preserves hint');
    for (const [hint, revision] of [['', 1], [' a ', 1], ['A\rB', 1], ['A\tB', 1], ['A\u007fB', 1], ['A\u0085B', 1], ['a'.repeat(601), 1], ['a', 0]]) {
      await assert.rejects(engine.query("UPDATE participant_daily_hints SET hint=$2,revision=$3 WHERE team_id=$1 AND participant_id='p1'", [a, hint, revision]));
    }
    await engine.query("UPDATE participant_daily_hints SET hint=$2 WHERE team_id=$1 AND participant_id='p1'", [a, '😀'.repeat(600)]);

    const before = new Date('2026-10-16T19:59:59.999Z'), midnight = new Date('2026-10-16T20:00:00Z');
    assert.equal((await readDailyHints(client, a, before)).day, '2026-10-16');
    await assert.rejects(saveDailyHint(client, a, { ...input, day: '2026-10-17', revision: 2 }, before), { status: 409 });
    await assert.rejects(saveDailyHint(client, a, { ...input, revision: 2 }, midnight), { status: 409 });
    assert.equal((await engine.query('SELECT count(*)::int AS n FROM participant_daily_hints')).rows[0].n, 3, 'stale-day rejection does not mutate rows');
    assert.deepEqual(await readDailyHints(client, a, midnight), { day: '2026-10-17', hints: [] });
    assert.equal((await engine.query('SELECT count(*)::int AS n FROM participant_daily_hints')).rows[0].n, 0, 'access prunes expired hints globally');
    await assert.rejects(saveDailyHint(client, a, { ...input, day: '2026-10-17', revision: 2 }, midnight), { status: 409 });
    assert.equal((await engine.query('SELECT count(*)::int AS n FROM participant_daily_hints')).rows[0].n, 0, 'nonzero revision cannot resurrect an expired hint');
    const today = { ...input, day: '2026-10-17' };
    assert.equal((await saveDailyHint(client, a, today, midnight)).hints[0].revision, 1);
    await assert.rejects(saveDailyHint(client, a, { ...input, revision: 1 }, midnight), { status: 409 });
    await saveDailyHint(client, b, today, midnight);
    await assert.rejects(saveDailyHint(client, a, { ...today, revision: 2 }, midnight), { status: 409 });
    assert.equal((await readDailyHints(client, a, midnight)).hints[0].revision, 1, 'failed CAS leaves winner untouched');

    // Saving, not just reading, globally expires old hints; current day survives.
    await engine.query("UPDATE participant_daily_hints SET day='2026-10-16' WHERE team_id=$1", [b]);
    await saveDailyHint(client, a, { ...today, revision: 1 }, midnight);
    assert.deepEqual(await readDailyHints(client, b, midnight), { day: today.day, hints: [] });
    await saveDailyHint(client, b, today, midnight);
    await engine.query('DELETE FROM teams WHERE id=$1', [a]);
    assert.equal((await engine.query('SELECT count(*)::int AS n FROM participant_daily_hints WHERE team_id=$1', [a])).rows[0].n, 0);
    assert.equal((await readDailyHints(client, b, midnight)).hints.length, 1, 'team deletion preserves other team');
    await engine.query("DELETE FROM participants WHERE team_id=$1 AND id='p1'", [b]);
    assert.equal((await readDailyHints(client, b, midnight)).hints.length, 0, 'identity deletion cascades');
  } finally { await engine.close(); }
});

test('daily hints API is no-store, same-origin, selected-team scoped and never read-cached', () => {
  const source = readFileSync(new URL('../src/app/api/daily-hints/route.ts', import.meta.url), 'utf8');
  assert.match(source, /'Cache-Control': 'no-store'/);
  assert.match(source, /sameOrigin\(request\)/);
  assert.match(source, /validateDailyHint\(await readJson\(request\)\)/);
  assert.equal(source.match(/await selectedTeam\(request\)/g)?.length, 2);
  assert.match(source, /teamReadCache\.mutate/);
  assert.doesNotMatch(source, /teamReadCache\.read|teamReadKey/);
});